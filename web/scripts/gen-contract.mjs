// Generates the TypeScript side of the contract from api/, into src/lib/contract/.
//
//   api/events.schema.json  ->  src/lib/contract/events.ts   (a type for every event, message and interaction)
//   api/openapi.yaml        ->  src/lib/contract/api.ts      (a type for every REST shape)
//   api/error-codes.json    ->  src/lib/contract/codes.ts    (the error and notice vocabulary, with copy)
//
// Run by `make gen` (pnpm gen:contract), which CI then diffs. A component may not hand-copy a type from these files: if it is not
// here, it is not in the contract (docs/STANDARDS.md 5).
import { compile } from 'json-schema-to-typescript';
import openapiTS, { astToString } from 'openapi-typescript';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const web = resolve(here, '..');
const repo = resolve(web, '..');
const out = resolve(web, 'src/lib/contract');
const banner = '// Code generated by tools/gen-ts.mjs from api/. DO NOT EDIT.\n\n';

await mkdir(out, { recursive: true });

// 1. The session protocol.
const schema = JSON.parse(await readFile(resolve(repo, 'api/events.schema.json'), 'utf8'));
const events = await compile(schema, 'CairnEvents', {
  bannerComment: banner,
  additionalProperties: false,
  style: { singleQuote: true },
  declareExternallyReferenced: true,
});
await writeFile(resolve(out, 'events.ts'), events);

// The schema itself, so the TypeScript validator reads the same document the Go one does. It is imported only by
// tests, so it never reaches the bundle.
await writeFile(resolve(out, 'schema.json'), JSON.stringify(schema, null, 2) + '\n');

// 2. The REST shapes.
const api = astToString(await openapiTS(new URL('file://' + resolve(repo, 'api/openapi.yaml'))));
await writeFile(resolve(out, 'api.ts'), banner + api);

// 3. The code vocabulary, with the copy the UI shows.
const registry = JSON.parse(await readFile(resolve(repo, 'api/error-codes.json'), 'utf8'));
const quote = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const codes = [
  banner +
    '// The stable codes and the words the UI shows for them. Never invent a code at a call site.',
  '',
  'export const errorCodes = {',
  ...registry.codes.map(
    (c) => `  ${quote(c.code)}: { status: ${c.status}, copy: ${quote(c.copy)} },`,
  ),
  '} as const;',
  '',
  'export type ErrorCode = keyof typeof errorCodes;',
  '',
  'export const noticeCodes = {',
  ...registry.notices.map(
    (n) => `  ${quote(n.code)}: { level: ${quote(n.level)}, copy: ${quote(n.copy)} },`,
  ),
  '} as const;',
  '',
  'export type NoticeCode = keyof typeof noticeCodes;',
  '',
  '/** Copy for a code this build does not know, which a newer server may send. */',
  'export function copyFor(code: string): string {',
  '  const known = errorCodes as Record<string, { copy: string }>;',
  "  return known[code]?.copy ?? 'Something went wrong. Try again.';",
  '}',
  '',
].join('\n');
await writeFile(resolve(out, 'codes.ts'), codes);

console.log('gen-contract: wrote src/lib/contract/{events,api,codes}.ts');
