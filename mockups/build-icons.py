#!/usr/bin/env python3
"""Regenerate icons.js, the Lucide sprite the mockups use.

Usage: python3 build-icons.py /path/to/unpacked/lucide-static/package
(get it with: npm pack lucide-static && tar -xzf lucide-static-*.tgz)

Each entry maps a short id used in the HTML (<use href="#i-ID">) to a Lucide icon name. In the real
app these come from @lucide/svelte instead; this file only exists so local mockups can use them.
"""
import json, re, sys

MAP = {
    "back": "chevron-left", "more": "ellipsis", "send": "arrow-up", "clip": "paperclip", "chev": "chevron-right",
    "check": "check", "dash": "circle-dashed", "img": "image", "read": "eye", "search": "search",
    "heart": "heart", "alert": "circle-alert", "star": "star",
    "info": "info", "pencil": "pencil", "history": "history", "link": "external-link", "x": "x",
    "library": "library", "sort": "arrow-up-down", "trash": "trash-2", "restore": "rotate-ccw", "plus": "plus",
    "wifioff": "wifi-off", "chat": "message-circle", "drafts": "file-pen-line",
}

src = sys.argv[1].rstrip("/") + "/icons/"
symbols = []
for ident, name in MAP.items():
    svg = open(src + name + ".svg", encoding="utf-8").read()
    inner = re.sub(r"\s+", " ", re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1).strip())
    symbols.append(f'<symbol class="lc" id="i-{ident}" viewBox="0 0 24 24">{inner}</symbol>')

# fill and stroke width are variables so a single icon can opt in (filled star, thinner star)
sprite = ('<svg width="0" height="0" style="position:absolute" aria-hidden="true"><defs>'
          '<style>.lc{fill:var(--lc-fill,none);stroke:currentColor;stroke-width:var(--lc-sw,1.75);'
          'stroke-linecap:round;stroke-linejoin:round}</style>' + "".join(symbols) + "</defs></svg>")
js = ("/* Lucide icons (ISC licence, lucide-static), injected as one sprite so local files can use them.\n"
      "   Generated by build-icons.py. In the real app these come from @lucide/svelte, bundled, never a CDN. */\n"
      "document.body.insertAdjacentHTML('afterbegin', " + json.dumps(sprite) + ");\n")
open("icons.js", "w", encoding="utf-8").write(js)
print(len(MAP), "icons,", len(js), "bytes")
